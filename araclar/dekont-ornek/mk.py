def scimg(name, rows, gen):
    W,H=2382,3368; im=Image.new('RGB',(W,H),'white'); d=ImageDraw.Draw(im)
    M='/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf'; fl=ImageFont.truetype(M,72); fa=ImageFont.truetype(F,78)
    d.text((130,140),"ShamCash",font=ImageFont.truetype(FB,110),fill='#0b2a3a'); d.line((130,380,W-130,380),fill='#999',width=4)
    y=520
    for lab,val in rows:
        d.text((130,y),lab,font=fl,fill='#3a5566')
        ar=any('؀'<=ch<='ۿ' for ch in val)
        f=fa if ar else fl
        w=d.textlength(val,font=f,direction='rtl' if ar else None,language='ar' if ar else None)
        d.text((W-130-w,y),val,font=f,fill='black',direction='rtl' if ar else None,language='ar' if ar else None)
        y+=230
    d.line((130,H-320,W-130,H-320),fill='#999',width=4)
    d.text((130,H-240),"GENERATED BY SHAMCASH",font=fl,fill='#3a5566'); w=d.textlength(gen,font=fl); d.text((W-130-w,H-240),gen,font=fl,fill='#3a5566')
    im.save(name,'PDF',resolution=288)
